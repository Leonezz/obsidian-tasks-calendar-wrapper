import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "module";
import { copyFileSync, mkdirSync, readFileSync, watchFile } from "fs";

/**
 * NOTICE, at the top of main.js: the MIT License asks that the copyright and permission notices of Obsidian Dataview
 * and Obsidian Tasks, whose code the bundle adapts, come with every copy. The build fails if either goes missing.
 */
const notice = readFileSync("../../NOTICE", "utf8");
for (const needed of [
	"Copyright (c) 2021 Michael Brenan, MIT License",
	"Copyright (c) 2021 Clare Macrae, Ilyas Landikov and Martin Schenck, MIT License",
	"Permission is hereby granted, free of charge",
]) {
	if (!notice.includes(needed)) throw new Error(`NOTICE no longer holds "${needed}", which main.js must carry.`);
}
if (notice.includes("*/")) throw new Error('NOTICE holds "*/", which would end the comment main.js carries it in.');

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

${notice.trimEnd()}
*/
`;

const prod = process.argv[2] === "production";

const manifestPath = "../../manifest.json";
/** The release workflow uploads main.js from here. */
const releaseDir = "dist";
/** `pnpm dev` builds into the example vault, in the folder named after the plugin id, as Obsidian installs it. */
const devPluginDir = `../../ExampleVault/.obsidian/plugins/${JSON.parse(readFileSync(manifestPath, "utf8")).id}`;

const pluginFiles = [manifestPath, "styles.css"];

/** Puts manifest.json and styles.css next to main.js in the example vault. */
function copyPluginFiles() {
	mkdirSync(devPluginDir, { recursive: true });
	for (const file of pluginFiles) copyFileSync(file, `${devPluginDir}/${file.split("/").pop()}`);
}

const copyPluginFilesAfterBuild = {
	name: "copy-plugin-files",
	setup(build) {
		build.onEnd(copyPluginFiles);
	},
};

/**
 * Fails the build if anything would bundle the npm moment. The plugin uses the moment Obsidian ships,
 * which follows the app language; a bundled copy adds its size and writes every date in English.
 */
const forbidNpmMoment = {
	name: "forbid-npm-moment",
	setup(build) {
		build.onResolve({ filter: /^moment(\/|$)/ }, (args) => ({
			errors: [
				{
					text: `${args.importer} imports "${args.path}" at runtime; use utils/moment, which is Obsidian's moment, or pass it in to core.`,
				},
			],
		}));
	},
};

/**
 * Fails the build if anything would bundle all of underscore, or Backbone, which brings it along. The plugin needs one
 * function of it, the comparison Backbone made of the timeline's list: underscore/modules/isEqual.js.
 */
const forbidWholeUnderscore = {
	name: "forbid-whole-underscore",
	setup(build) {
		build.onResolve({ filter: /^(underscore|backbone)$/ }, (args) => ({
			errors: [
				{
					text: `${args.importer} imports "${args.path}"; import the function from underscore/modules/<name>.js, so the bundle does not carry the whole library.`,
				},
			],
		}));
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	define: {
		"process.env.NODE_ENV": JSON.stringify(prod ? "production" : "development"),
	},
	external: [
		"obsidian",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: `${prod ? releaseDir : devPluginDir}/main.js`,
	plugins: prod
		? [forbidNpmMoment, forbidWholeUnderscore]
		: [forbidNpmMoment, forbidWholeUnderscore, copyPluginFilesAfterBuild],
});

if (prod) {
	await context.rebuild();
	// Esbuild writes these filenames in path comments, which minify drops.
	// React's key warning is a string only development builds hold, so it survives minify.
	const bundle = readFileSync(`${releaseDir}/main.js`, "utf8");
	for (const developmentMarker of [
		"react.development.js",
		"react-dom.development.js",
		"react-jsx-runtime.development.js",
		"scheduler.development.js",
		'Each child in a list should have a unique "key" prop',
	]) {
		if (bundle.includes(developmentMarker))
			throw new Error(
				`main.js contains "${developmentMarker}"; define process.env.NODE_ENV as "production" so the release bundles React's production builds.`,
			);
	}
	process.exit(0);
} else {
	await context.watch();
	// Neither file is part of the bundle, so esbuild does not rebuild when they change. Polling also survives editors that replace the file on save.
	for (const file of pluginFiles) watchFile(file, { interval: 500 }, copyPluginFiles);
}
